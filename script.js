const speechList = document.querySelector("#speech-list");
const searchInput = document.querySelector("#speech-search");
const resultsCount = document.querySelector("#results-count");
const emptyState = document.querySelector("#empty-state");
const filterButtons = [...document.querySelectorAll(".filter-chip")];
let activeFilter = "all";

function wordCount(paragraphs) {
  return paragraphs.join(" ").trim().split(/\s+/).length;
}

function renderSpeeches() {
  speechList.innerHTML = speeches.map((speech, index) => {
    const words = wordCount(speech.paragraphs);
    const searchText = `${speech.title} ${speech.label} ${speech.paragraphs.join(" ")}`.toLowerCase();
    return `
      <details class="speech-card" data-theme="${speech.theme}" data-search="${searchText.replaceAll('"', "&quot;")}">
        <summary class="speech-summary">
          <span class="speech-number">${String(index + 1).padStart(2, "0")}</span>
          <span class="speech-title-wrap">
            <span class="speech-title">${speech.title}</span>
            <span class="speech-theme">${speech.label}</span>
          </span>
          <span class="speech-meta">
            <span class="speech-time">${Math.max(2, Math.ceil(words / 130))} min read</span>
            <span class="speech-toggle" aria-hidden="true">+</span>
          </span>
        </summary>
        <div class="speech-body">
          ${speech.paragraphs.map(paragraph => `<p>${paragraph}</p>`).join("")}
          <div class="speech-footer">
            <span class="speech-word-count">${words} words · original speech</span>
            <button class="copy-button" type="button">Copy speech</button>
          </div>
        </div>
      </details>`;
  }).join("");
}

function filterSpeeches() {
  const query = searchInput.value.trim().toLowerCase();
  let visibleCount = 0;
  for (const card of speechList.querySelectorAll(".speech-card")) {
    const matchesTheme = activeFilter === "all" || card.dataset.theme === activeFilter;
    const matchesSearch = !query || card.dataset.search.includes(query);
    card.hidden = !(matchesTheme && matchesSearch);
    if (!card.hidden) visibleCount++;
  }
  resultsCount.textContent = visibleCount === 10 && activeFilter === "all" && !query
    ? "Showing all 10 speeches"
    : `Showing ${visibleCount} ${visibleCount === 1 ? "speech" : "speeches"}`;
  emptyState.hidden = visibleCount !== 0;
}

renderSpeeches();
filterSpeeches();
searchInput.addEventListener("input", filterSpeeches);

for (const button of filterButtons) {
  button.addEventListener("click", () => {
    activeFilter = button.dataset.filter;
    for (const chip of filterButtons) {
      const selected = chip === button;
      chip.classList.toggle("is-active", selected);
      chip.setAttribute("aria-pressed", String(selected));
    }
    filterSpeeches();
  });
}

speechList.addEventListener("click", async event => {
  const button = event.target.closest(".copy-button");
  if (!button) return;
  const card = button.closest(".speech-card");
  const speechIndex = [...speechList.querySelectorAll(".speech-card")].indexOf(card);
  const speech = speeches[speechIndex];
  const text = `${speech.title}\n\n${speech.paragraphs.join("\n\n")}`;
  try {
    await navigator.clipboard.writeText(text);
    button.textContent = "Copied!";
    window.setTimeout(() => { button.textContent = "Copy speech"; }, 1800);
  } catch (error) {
    button.textContent = "Copy unavailable";
    window.setTimeout(() => { button.textContent = "Copy speech"; }, 2200);
  }
});

document.addEventListener("keydown", event => {
  if (event.key === "/" && !["INPUT", "TEXTAREA"].includes(document.activeElement.tagName)) {
    event.preventDefault();
    searchInput.focus();
  }
  if (event.key === "Escape" && document.activeElement === searchInput) {
    searchInput.value = "";
    searchInput.blur();
    filterSpeeches();
  }
});

const menuToggle = document.querySelector(".menu-toggle");
const mainNav = document.querySelector(".main-nav");
menuToggle.addEventListener("click", () => {
  const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!isOpen));
  menuToggle.setAttribute("aria-label", isOpen ? "Open menu" : "Close menu");
  mainNav.classList.toggle("is-open", !isOpen);
});
mainNav.addEventListener("click", event => {
  if (event.target.closest("a")) {
    mainNav.classList.remove("is-open");
    menuToggle.setAttribute("aria-expanded", "false");
    menuToggle.setAttribute("aria-label", "Open menu");
  }
});
